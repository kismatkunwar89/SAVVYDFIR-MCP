def test_source_text_helper_is_strict():
    """Source-text guard: _execution_id_resolvable must NOT use
    requires_re_extraction as a bypass. The function should reject the
    pattern that returns True on requires_re_extraction."""
    import inspect
    from sift_mcp.semantics import _execution_id_resolvable
    src = inspect.getsource(_execution_id_resolvable)
    # The bypass pattern must be GONE
    assert 'finding.get("requires_re_extraction")' not in src, (
        "peer reviewer consensus regression: _execution_id_resolvable must not "
        "treat requires_re_extraction as a finding-level bypass. Operator "
        "override happens at report layer via allow_partial=True."
    )
    # Must check execution_id_source = state_autogenerated
    assert "state_autogenerated" in src, (
        "Helper must reject autogenerated execution_ids that lack audit links."
    )
