class _FakeStateManager:
    """Minimal stand-in supporting get_execution for the gate tests."""
    def __init__(self, executions: dict[str, dict[str, Any]] | None = None):
        self._execs = dict(executions or {})

    def get_execution(self, eid: str):
        return self._execs.get(eid)


def _import_helper():
    from sift_mcp.semantics import _execution_id_resolvable
    return _execution_id_resolvable


def test_resolvable_requires_real_execution_id():
    """Placeholder E-000 must fail the gate."""
    helper = _import_helper()
    sm = _FakeStateManager({"E-001": {"tool_name": "disk.x"}})
    ok, reason = helper({"execution_id": "E-000"}, sm)
    assert not ok
    assert "placeholder" in reason or "missing" in reason


def test_resolvable_rejects_autogenerated_execution_id():
    """state_autogenerated execution_id_source must fail the gate."""
    helper = _import_helper()
    sm = _FakeStateManager({"E-007": {"tool_name": "disk.x"}})
    ok, reason = helper({
        "execution_id": "E-007",
        "confidence_support_inputs": {"execution_id_source": "state_autogenerated"},
    }, sm)
    assert not ok
    assert "autogenerated" in reason


def test_resolvable_passes_when_audit_row_exists():
    """A real execution_id matching an audit row passes the gate."""
    helper = _import_helper()
    sm = _FakeStateManager({"E-042": {"tool_name": "disk.extract_mft_timeline"}})
    ok, reason = helper({"execution_id": "E-042"}, sm)
    assert ok
    assert reason == "ok"


def test_resolvable_fails_when_audit_row_missing():
    """Real-looking execution_id that doesn't resolve in the ledger fails."""
    helper = _import_helper()
    sm = _FakeStateManager({"E-001": {"tool_name": "disk.x"}})
    ok, reason = helper({"execution_id": "E-999"}, sm)
    assert not ok
    assert "unresolvable" in reason


def test_resolvable_no_state_manager_context_passes():
    """Migration / isolated test mode: no state_manager → accept (defense
    is at report layer)."""
    helper = _import_helper()
    ok, reason = helper({"execution_id": "E-001"}, None)
    assert ok
    assert "no_state_manager_context" in reason


def test_requires_re_extraction_is_not_a_bypass():
    """Critical: requires_re_extraction=True must NOT bypass the gate.
    The flag is a state marker; operator override happens at report level."""
    helper = _import_helper()
    sm = _FakeStateManager({"E-001": {"tool_name": "disk.x"}})
    ok, reason = helper({
        "execution_id": "E-000",
        "requires_re_extraction": True,
    }, sm)
    assert not ok, (
        "requires_re_extraction must NOT be a bypass at the finding-level "
        "gate. Operator override happens via allow_partial=True at report level."
    )


