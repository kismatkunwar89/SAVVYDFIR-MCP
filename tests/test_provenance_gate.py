def test_validate_and_prepare_demotes_confirmed_on_provenance_failure():
    """A CONFIRMED finding with a non-resolvable execution_id must be
    demoted to ACTIVE and have requires_re_extraction set."""
    from sift_mcp.semantics import validate_and_prepare_finding
    sm = _FakeStateManager({})  # empty ledger — no execution resolves
    incoming = {
        "case_id": "TEST",
        "finding_type": "test_finding",
        "tool_name": "test.tool",
        "execution_id": "E-999",   # not in ledger
        "iteration": 1,
        "evidence_kind": "INFERENCE",
        "finding_status": "CONFIRMED",  # caller tried to promote
        "confidence": 0.95,
        "description": "Test finding for provenance gate regression.",
        "artifact_path": "/test/artifact.csv",
        "artifact_type": "memory",
    }
    out = validate_and_prepare_finding(incoming, state_manager=sm)
    assert out["finding_status"] == "ACTIVE", (
        f"Finding must be demoted from CONFIRMED to ACTIVE when execution_id "
        f"does not resolve. Got: {out['finding_status']}"
    )
    assert out.get("requires_re_extraction") is True, (
        "Demoted finding must carry requires_re_extraction=True as a state marker."
    )
    blocks = (out.get("confidence_support_inputs") or {}).get("confirmed_gate_blocks") or []
    assert any("provenance:" in b for b in blocks), (
        f"confirmed_gate_blocks must record the provenance reason. Got: {blocks}"
    )


