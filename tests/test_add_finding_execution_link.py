def test_state_add_finding_links_to_latest_execution_source_check():
    """Source-text guard: state.add_finding must search self._state['executions']
    for the most recent matching execution before falling back to
    generate_execution_id (the autogen path that produced orphan IDs)."""
    src = (ROOT / "sift_mcp" / "state.py").read_text()
    func_idx = src.find("def add_finding(self, finding")
    assert func_idx > 0
    end = src.find("\n    def ", func_idx + 1)
    body = src[func_idx:end if end > 0 else func_idx + 6000]

    assert "auto_linked_same_tool_execution" in body, (
        "add_finding must mark linked execution_ids with the "
        "'auto_linked_same_tool_execution' source so audit consumers "
        "can distinguish them from operator-supplied IDs."
    )
    assert "auto_linked_latest_tool_execution" in body, (
        "add_finding must fall back to the latest execution overall "
        "when no same-tool execution exists, marked as "
        "'auto_linked_latest_tool_execution'."
    )
    # autogen path must still exist as the final fallback (empty executions list)
    autogen_idx = body.find("state_autogenerated")
    same_tool_idx = body.find("auto_linked_same_tool_execution")
    assert 0 < same_tool_idx < autogen_idx, (
        "The link-to-real-execution path must run BEFORE the autogen "
        "fallback, otherwise we keep producing orphan IDs."
    )


def test_add_finding_mcp_tool_exposes_alt_hypothesis_params():
    """Source-text guard: the add_finding MCP tool must declare the 6 new
    parameters as part of its signature (so the agent can populate them
    via the tool call surface without the corroboration-analyst subagent)."""
    src = (ROOT / "sift_mcp" / "server.py").read_text()
    sig_idx = src.find("def add_finding(\n    case_id: str,")
    assert sig_idx > 0
    sig_end = src.find(") -> dict[str, Any]:", sig_idx)
    sig_block = src[sig_idx:sig_end]
    required_params = (
        "execution_id: str",
        "alternative_hypothesis: str",
        "evidence_that_would_support_it",
        "evidence_against_it",
        "disposition: str",
        "alternative_hypothesis_not_applicable_reason: str",
    )
    for param in required_params:
        assert param in sig_block, (
            f"add_finding MCP signature is missing required parameter: {param}. "
            f"Without it, Path B (main-agent inline) cannot populate the "
            f"alt-hypothesis fields and every CONFIRMED finding will be "
            f"demoted by the A2 gate."
        )


