"""Regression tests for the add_finding execution_id auto-link + alt-hypothesis schema.

peer reviewer consensus 2026-05-19 follow-up: Run-11 produced 0 CONFIRMED findings
because the framework's add_finding auto-generated orphan execution_ids
(no audit link) AND the alt-hypothesis fields were not reachable from
the MCP add_finding tool surface (only via the corroboration-analyst
subagent, which was unavailable that run).

These tests prove the fix:
  1. add_finding auto-links missing execution_id to the most recent
     execution row (preferring same tool_name), eliminating the
     "execution_id_autogenerated_no_audit_link" gate block.
  2. The add_finding MCP tool exposes the 5 alt-hypothesis fields +
     explicit execution_id parameter so main-agent (Path B) can
     populate them inline.
  3. A CONFIRMED finding created via add_finding with full alt-hypothesis
     fields survives both gates and stays CONFIRMED.
"""
