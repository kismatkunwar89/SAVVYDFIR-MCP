def test_validate_path_does_not_collide_with_state_autogen(tmp_path):
    """Ensure that when add_finding auto-links to a real execution and then
    re-validates, the gate sees the linked eid (not E-000) and the finding
    passes the resolvability check."""
    from sift_mcp.semantics import _execution_id_resolvable

    sm = _make_state(tmp_path)
    _record_execution(sm, "E-007", "memory.list_processes")
    finding = {
        "case_id": "TEST-CASE",
        "finding_type": "process",
        "tool_name": "memory.list_processes",
        "artifact_path": "/test/pslist.csv",
        "artifact_type": "process",
        "evidence_kind": "MEMORY_ARTIFACT",
        "description": "rogue process",
        "confidence": 0.8,
        "finding_status": "ACTIVE",
        "iteration": 1,
    }
    fid = sm.add_finding(finding)
    stored = sm.get_finding(fid)
    ok, reason = _execution_id_resolvable(stored, sm)
    assert ok, (
        f"Auto-linked execution_id must resolve through the gate. "
        f"Got reason={reason!r}"
    )
