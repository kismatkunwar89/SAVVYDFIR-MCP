def test_explicit_execution_id_is_respected(tmp_path):
    """If the agent supplies an explicit execution_id, the framework must
    use it verbatim (no auto-link override)."""
    sm = _make_state(tmp_path)
    _record_execution(sm, "E-001", "memory.list_processes")
    _record_execution(sm, "E-042", "disk.extract_mft_timeline")

    finding = {
        "case_id": "TEST-CASE",
        "finding_type": "test",
        "tool_name": "disk.extract_mft_timeline",
        "artifact_path": "/test/mft.csv",
        "artifact_type": "filesystem",
        "evidence_kind": "DISK_ARTIFACT",
        "description": "Explicit-eid finding",
        "confidence": 0.9,
        "execution_id": "E-042",
        "finding_status": "ACTIVE",
        "iteration": 1,
    }
    fid = sm.add_finding(finding)
    stored = sm.get_finding(fid)
    assert stored["execution_id"] == "E-042"
    # No autogen / auto-link source marker should be inserted
    src = (stored.get("confidence_support_inputs") or {}).get("execution_id_source")
    assert src in (None, "operator_supplied"), (
        f"Explicit execution_id should not get a state_autogenerated source. Got {src!r}"
    )


def test_confirmed_finding_with_linked_eid_and_alt_hypothesis_stays_confirmed(tmp_path):
    """The end-to-end fix: a CONFIRMED finding created with auto-linked
    execution_id + full alt-hypothesis fields must survive BOTH gates
    and stay CONFIRMED. This is what Run-11 needed but couldn't do."""
    sm = _make_state(tmp_path)
    _record_execution(sm, "E-001", "disk.summarize_evtx")

    finding = {
        "case_id": "TEST-CASE",
        "finding_type": "service_install",
        "tool_name": "disk.summarize_evtx",
        "artifact_path": "/test/System.evtx",
        "artifact_type": "evtx_event",
        "evidence_kind": "DISK_ARTIFACT",
        "description": "System.evtx EID 7045 service install correlated with MFT/USN drop",
        "confidence": 0.95,
        "finding_status": "CONFIRMED",
        "iteration": 1,
        "alternative_hypothesis": "Legitimate IT-deployed remote forensics agent",
        "evidence_against_it": [
            "no change-management ticket present in /etc/ITSM/tickets",
            "binary dropped from C:/Users/Public/Downloads — not standard IT path",
            "service install occurred outside business hours (03:01 UTC)",
        ],
        "disposition": "ruled_out",
    }
    fid = sm.add_finding(finding)
    stored = sm.get_finding(fid)
    assert stored["finding_status"] == "CONFIRMED", (
        "CONFIRMED finding with valid linked execution_id + full alt-hypothesis "
        "must survive both gates. This is the failure mode Run-11 exhibited."
    )
    assert not stored.get("requires_re_extraction"), (
        "requires_re_extraction must NOT be set when both gates pass."
    )
    assert stored["execution_id"] == "E-001"


